-- Presentation-ready results from the final detrended resilience view.
-- Run the whole worksheet. The first result supplies the headline numbers;
-- the second supplies candidate country examples for the presentation.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE FAOSTAT_WH;
USE DATABASE FAOSTAT_DB;
USE SCHEMA ANALYTICS;

WITH analyzable AS (
  SELECT *
  FROM ANALYTICS.VW_EVENT_PRODUCTION_RESILIENCE
  WHERE BASELINE_YEAR_COUNT >= 2
    AND EVENT_YEAR_INDEX IS NOT NULL
),
summary AS (
  SELECT
    COUNT(*) AS ANALYZABLE_COUNTRY_EVENT_YEARS,
    COUNT_IF(WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 IS NOT NULL)
      AS CASES_WITH_DETRENDED_SHOCK,
    COUNT_IF(
      WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 IS NOT NULL
      AND UNDERNOURISHMENT_PERCENT IS NOT NULL
    ) AS CORRELATION_SAMPLE_SIZE,
    CORR(
      UNDERNOURISHMENT_PERCENT,
      WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1
    ) AS DETRENDED_CORRELATION,
    COUNT_IF(
      WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 <= -10
      AND UNDERNOURISHMENT_PERCENT >= 20
      AND RECOVERY_STATUS = 'NOT_RECOVERED_WITHIN_3_YEARS'
    ) AS PRIORITY_CASES,
    COUNT(DISTINCT IFF(
      WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 <= -10
      AND UNDERNOURISHMENT_PERCENT >= 20
      AND RECOVERY_STATUS = 'NOT_RECOVERED_WITHIN_3_YEARS',
      ISO3,
      NULL
    )) AS PRIORITY_COUNTRIES
  FROM analyzable
)
SELECT
  ANALYZABLE_COUNTRY_EVENT_YEARS,
  CASES_WITH_DETRENDED_SHOCK,
  CORRELATION_SAMPLE_SIZE,
  ROUND(DETRENDED_CORRELATION, 3) AS DETRENDED_CORRELATION_R,
  ROUND(POWER(DETRENDED_CORRELATION, 2), 3) AS DETRENDED_R_SQUARED,
  PRIORITY_COUNTRIES,
  PRIORITY_CASES
FROM summary;

-- Candidate examples. Review data cautions and contextual explanations before
-- choosing the final two or three; these are priority-screening cases, not causal claims.
SELECT
  COUNTRY,
  ISO3,
  EVENT_YEAR,
  EVENT_TYPES,
  ROUND(WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1, 1) AS DETRENDED_SHOCK_PERCENT,
  ROUND(UNDERNOURISHMENT_PERCENT, 1) AS UNDERNOURISHMENT_PERCENT,
  UNDERNOURISHMENT_IS_UPPER_BOUND,
  RECOVERY_STATUS,
  RECOVERY_YEARS,
  TOTAL_AFFECTED_REPORTED,
  TOTAL_DEATHS_REPORTED,
  TOTAL_DAMAGE_ADJUSTED_000_USD
FROM ANALYTICS.VW_EVENT_PRODUCTION_RESILIENCE
WHERE BASELINE_YEAR_COUNT >= 2
  AND EVENT_YEAR_INDEX IS NOT NULL
  AND WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 <= -10
  AND UNDERNOURISHMENT_PERCENT >= 20
  AND RECOVERY_STATUS = 'NOT_RECOVERED_WITHIN_3_YEARS'
ORDER BY
  WORST_DETRENDED_CHANGE_PERCENT_T_TO_T1 ASC,
  UNDERNOURISHMENT_PERCENT DESC,
  COUNTRY,
  EVENT_YEAR
LIMIT 20;

